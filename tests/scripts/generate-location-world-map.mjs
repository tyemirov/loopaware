// @ts-check

import * as fs from 'node:fs';
import * as path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { geoEquirectangular, geoPath } from 'd3-geo';

const require = createRequire(import.meta.url);
const scriptPath = fileURLToPath(import.meta.url);
const scriptDirectory = path.dirname(scriptPath);
const repositoryRoot = path.resolve(scriptDirectory, '..', '..');
const dashboardPath = path.join(repositoryRoot, 'web', 'app', 'index.html');
const landTopologyPath = require.resolve('world-atlas/land-110m.json');
const topojsonClient = require('topojson-client');

const mapWidth = 720;
const mapHeight = 300;
const minimumPathLength = 1000;
const pathChunkLength = 960;
const generatedComment = '        // Generated by tests/scripts/generate-location-world-map.mjs from world-atlas Natural Earth data.';
const blockEnd = '        // End generated location world map.';
const mobileMapPath = path.join(repositoryRoot, 'mobile', 'src', 'location-world.ts');
const projectionBody = `
  var longitude = Math.max(-180, Math.min(180, coordinates.longitude));
  var latitude = Math.max(-80, Math.min(84, coordinates.latitude));
  var projectedDegreeSize = locationMapHeight / 180;
  return {
    x: (locationMapWidth / 2) + (longitude * projectedDegreeSize),
    y: (locationMapHeight / 2) - (latitude * projectedDegreeSize)
  };
`;

function readLandTopology() {
  const rawTopology = JSON.parse(fs.readFileSync(landTopologyPath, 'utf8'));
  if (!rawTopology.objects || !rawTopology.objects.land) {
    throw new Error('location_map_generator:missing_land_topology_object');
  }
  return rawTopology;
}

function buildWorldLandPath() {
  const landTopology = readLandTopology();
  const projection = geoEquirectangular()
    .scale(mapHeight / Math.PI)
    .translate([mapWidth / 2, mapHeight / 2])
    .precision(0.1);
  const pathGenerator = geoPath(projection).digits(0);
  const landFeature = topojsonClient.feature(landTopology, landTopology.objects.land);
  const pathData = pathGenerator(landFeature);
  if (!pathData || pathData.length < minimumPathLength) {
    throw new Error('location_map_generator:invalid_land_path');
  }
  if (pathData.includes("'")) {
    throw new Error('location_map_generator:unsupported_land_path_quote');
  }
  return pathData;
}

function chunkString(value) {
  const chunks = [];
  for (let offset = 0; offset < value.length; offset += pathChunkLength) {
    chunks.push(value.slice(offset, offset + pathChunkLength));
  }
  return chunks;
}

function buildGeneratedBlock(pathData) {
  const lines = [generatedComment, '        var locationWorldLandPath = ['];
  const chunks = chunkString(pathData);
  chunks.forEach((chunk, index) => {
    const suffix = index === chunks.length - 1 ? '' : ',';
    lines.push(`          '${chunk}'${suffix}`);
  });
  lines.push("        ].join('');");
  lines.push(`        var locationMapWidth = ${mapWidth};`, `        var locationMapHeight = ${mapHeight};`);
  lines.push('        /** @param {{latitude:number, longitude:number}} coordinates */');
  lines.push('        function projectLocationCoordinates(coordinates) {' + projectionBody.replace(/\n(?=.)/g, '\n        ') + '        }');
  lines.push(blockEnd);
  return lines.join('\n');
}

function findWorldMapBlock(source) {
  const generatedStart = source.indexOf(generatedComment);
  if (generatedStart === -1) {
    throw new Error('location_map_generator:missing_world_map_block');
  }
  const end = source.indexOf(blockEnd, generatedStart);
  if (end === -1) {
    throw new Error('location_map_generator:unterminated_world_map_block');
  }
  return { start: generatedStart, end: end + blockEnd.length };
}

function updateMaps(checkOnly) {
  const source = fs.readFileSync(dashboardPath, 'utf8');
  const pathData = buildWorldLandPath();
  const generatedBlock = buildGeneratedBlock(pathData);
  const block = findWorldMapBlock(source);
  const nextSource = source.slice(0, block.start) + generatedBlock + source.slice(block.end);
  const mobileSource = `// Generated by tests/scripts/generate-location-world-map.mjs from world-atlas Natural Earth data.
export const locationMapWidth = ${mapWidth};
export const locationMapHeight = ${mapHeight};
export const locationWorldLandPath = ${JSON.stringify(pathData)};
export function projectLocationCoordinates(coordinates: {latitude: number; longitude: number}): {x: number; y: number} {${projectionBody}}
`;
  for (const [destination, expected] of [[dashboardPath, nextSource], [mobileMapPath, mobileSource]]) {
    const current = fs.existsSync(destination) ? fs.readFileSync(destination, 'utf8') : '';
    if (current === expected) continue;
    if (checkOnly) {
      console.error(`location world map is stale: ${path.relative(repositoryRoot, destination)}. Run npm --prefix tests run generate:location-map.`);
      process.exitCode = 1;
    } else {
      fs.writeFileSync(destination, expected);
      console.log(`updated location world map: ${path.relative(repositoryRoot, destination)}`);
    }
  }
}

updateMaps(process.argv.includes('--check'));
